/** A prefix shared by every instance curve of the pattern `patternId`. */
export function sketchPatternInstancePrefix(patternId: string): string {
  const suffix = patternId.slice(patternId.indexOf(":") + 1).toLowerCase().replace(/[^a-z0-9-]/gu, "-");
  return `entity:pat.${suffix}.`;
}

/** ID of the curve made from source number `sourceIndex` in instance `instance` of the pattern. */
export function sketchPatternInstanceEntityId(patternId: string, instance: number, sourceIndex: number): string {
  return `${sketchPatternInstancePrefix(patternId)}${instance}.${sourceIndex}`;
}

/** Which instance a pattern curve belongs to, or undefined when the ID is not one of this pattern's. */
export function sketchPatternInstanceOf(patternId: string, entityId: string): number | undefined {
  const prefix = sketchPatternInstancePrefix(patternId);
  if (!entityId.startsWith(prefix)) return undefined;
  const parts = entityId.slice(prefix.length).split(".");
  const instance = Number(parts[0]);
  return Number.isInteger(instance) && parts.length === 2 ? instance : undefined;
}

export interface SketchPatternPlacement {
  /** Instance number, 1 and up. */
  readonly instance: number;
  /** Maps a point of the source to its place in this instance. */
  readonly point: (value: Vec2) => Vec2;
  /** Turn applied to rotation fields. */
  readonly turnDeg: number;
}

export type SketchPatternPlacementResult =
  | { readonly ok: true; readonly placements: readonly SketchPatternPlacement[] }
  | { readonly ok: false; readonly message: string };

const bad = (message: string): { readonly ok: false; readonly message: string } => ({ ok: false, message });

function rotateAbout(center: Vec2, radians: number): (value: Vec2) => Vec2 {
  const cos = Math.cos(radians);
  const sin = Math.sin(radians);
  return (value) => [center[0] + (value[0] - center[0]) * cos - (value[1] - center[1]) * sin, center[1] + (value[0] - center[0]) * sin + (value[1] - center[1]) * cos];
}

/**
 * The placement of every instance (not the source) of a pattern layout. `sources` give the reference point of the path and
 * circular layouts; `entities` is the sketch (to find the path curve). Returns a message when the layout cannot be built.
 */
export function sketchPatternPlacements(spec: SketchPatternSpec, sources: readonly SketchEntity[], entities: readonly SketchEntity[]): SketchPatternPlacementResult {
  const placements: SketchPatternPlacement[] = [];
  if (spec.kind === "rectangular") {
    const { countX, countY } = spec;
    if (!integer(countX, 1, SKETCH_PATTERN_MAX_INSTANCES) || !integer(countY, 1, SKETCH_PATTERN_MAX_INSTANCES) || countX * countY < 2) return bad("Enter whole-number counts of at least 1, with at least 2 instances in total.");
    if (countX * countY > SKETCH_PATTERN_MAX_INSTANCES) return bad(`A pattern is limited to ${SKETCH_PATTERN_MAX_INSTANCES} instances.`);
    if (!Number.isFinite(spec.dxMm) || !Number.isFinite(spec.dyMm) || !Number.isFinite(spec.angleDeg)) return bad("The pattern spacing and direction must be numbers.");
    const stepX = spec.extent ? (countX > 1 ? spec.dxMm / (countX - 1) : 0) : spec.dxMm;
    const stepY = spec.extent ? (countY > 1 ? spec.dyMm / (countY - 1) : 0) : spec.dyMm;
    if ((countX > 1 && Math.abs(stepX) < 0.01) || (countY > 1 && Math.abs(stepY) < 0.01)) return bad("Enter a spacing of at least 0.01 mm in each direction that has more than one instance.");
    const radians = (spec.angleDeg * Math.PI) / 180;
    const ux: Vec2 = [Math.cos(radians), Math.sin(radians)];
    const uy: Vec2 = [-Math.sin(radians), Math.cos(radians)];
    for (let row = 0; row < countY; row += 1) {
      for (let column = 0; column < countX; column += 1) {
        if (row === 0 && column === 0) continue;
        const dx = column * stepX * ux[0] + row * stepY * uy[0];
        const dy = column * stepX * ux[1] + row * stepY * uy[1];
        placements.push({ instance: row * countX + column, point: (value) => [value[0] + dx, value[1] + dy], turnDeg: 0 });
      }
    }
    return { ok: true, placements };
  }
  if (spec.kind === "circular") {
    if (!integer(spec.count, 2, SKETCH_PATTERN_MAX_INSTANCES)) return bad(`Enter a count from 2 to ${SKETCH_PATTERN_MAX_INSTANCES}.`);
    if (!Number.isFinite(spec.angleDeg) || Math.abs(spec.angleDeg) < 0.01 || Math.abs(spec.angleDeg) > 360) return bad("Enter a total angle between 0.01 and 360 degrees.");
    if (!Number.isFinite(spec.center[0]) || !Number.isFinite(spec.center[1])) return bad("The pattern centre must be a point.");
    const step = Math.abs(spec.angleDeg) >= 360 - 1e-9 ? spec.angleDeg / spec.count : spec.angleDeg / (spec.count - 1);
    const box = boundsOfEntities(sources);
    const reference: Vec2 = [(box.min[0] + box.max[0]) / 2, (box.min[1] + box.max[1]) / 2];
    for (let index = 1; index < spec.count; index += 1) {
      const radians = (step * index * Math.PI) / 180;
      const turn = rotateAbout(spec.center, radians);
      if (spec.rotate) placements.push({ instance: index, point: turn, turnDeg: step * index });
      else {
        const moved = turn(reference);
        const dx = moved[0] - reference[0];
        const dy = moved[1] - reference[1];
        placements.push({ instance: index, point: (value) => [value[0] + dx, value[1] + dy], turnDeg: 0 });
      }
    }
    return { ok: true, placements };
  }
  // Path layout.
  if (!integer(spec.count, 2, SKETCH_PATTERN_MAX_INSTANCES)) return bad(`Enter a count from 2 to ${SKETCH_PATTERN_MAX_INSTANCES}.`);
  const pathEntity = entities.find((entity) => entity.id === spec.pathEntityId);
  if (pathEntity === undefined) return bad("The path curve of this pattern no longer exists.");
  const path = sketchPathPolyline(pathEntity);
  if (path === undefined) return bad(`A ${pathEntity.kind} cannot be a pattern path; pick a line, arc, circle, ellipse, rectangle or spline.`);
  if (!Number.isFinite(spec.startMm) || spec.startMm < 0 || spec.startMm >= path.totalMm) return bad(`The start distance must lie on the path (0 to ${round(path.totalMm)} mm).`);
  const available = path.closed ? path.totalMm : path.totalMm - spec.startMm;
  const step = spec.fit ? (path.closed ? available / spec.count : available / (spec.count - 1)) : spec.spacingMm;
  if (!Number.isFinite(step) || step < 0.01) return bad("Enter a spacing along the path of at least 0.01 mm.");
  const needed = (spec.count - 1) * step;
  if (!path.closed && needed > available + 1e-6) return bad(`The pattern needs ${round(needed)} mm of path but only ${round(available)} mm is left after the start. Use fewer instances, a smaller spacing or Fit.`);
  if (path.closed && !spec.fit && needed >= path.totalMm - 1e-6) return bad(`The instances would overlap: ${spec.count} steps of ${round(step)} mm exceed the ${round(path.totalMm)} mm round the path. Use fewer instances or a smaller spacing.`);
  const box = boundsOfEntities(sources);
  const reference: Vec2 = [(box.min[0] + box.max[0]) / 2, (box.min[1] + box.max[1]) / 2];
  const first = sketchPathPointAt(path, spec.startMm);
  for (let index = 1; index < spec.count; index += 1) {
    const here = sketchPathPointAt(path, spec.startMm + index * step);
    const dx = here.point[0] - first.point[0];
    const dy = here.point[1] - first.point[1];
    if (spec.follow) {
      const turnRadians = here.angle - first.angle;
      const turn = rotateAbout(reference, turnRadians);
      placements.push({ instance: index, point: (value) => { const turned = turn(value); return [turned[0] + dx, turned[1] + dy]; }, turnDeg: (turnRadians * 180) / Math.PI });
    } else placements.push({ instance: index, point: (value) => [value[0] + dx, value[1] + dy], turnDeg: 0 });
  }
  return { ok: true, placements };
}

function round(value: number): number {
  return Math.round(value * 1000) / 1000;
}

export type SketchPatternGeneration =
  | { readonly ok: true; readonly entities: readonly SketchEntity[] }
  | { readonly ok: false; readonly message: string };

/** Every instance curve of a pattern (suppressed instances left out), with their deterministic IDs. */
export function generateSketchPatternEntities(pattern: SketchPatternObject, entities: readonly SketchEntity[]): SketchPatternGeneration {
  const sources = pattern.sourceIds.map((id) => entities.find((entity) => entity.id === id));
  if (sources.some((entity) => entity === undefined)) return bad("A source curve of this pattern no longer exists.");
  const present = sources as SketchEntity[];
  if (pattern.spec.kind === "path" && present.some((entity) => entity.id === (pattern.spec as { readonly pathEntityId: string }).pathEntityId)) return bad("The path of a path pattern cannot also be repeated.");
  const placed = sketchPatternPlacements(pattern.spec, present, entities);
  if (!placed.ok) return placed;
  const result: SketchEntity[] = [];
  const skipped = new Set(pattern.suppressed);
  for (const placement of placed.placements) {
    if (skipped.has(placement.instance)) continue;
    present.forEach((source, index) => {
      result.push(transformSketchEntity(source, sketchPatternInstanceEntityId(pattern.id, placement.instance, index), placement.point, placement.turnDeg));
    });
  }
  return { ok: true, entities: result };
}

/** How many instances (the source included) a layout makes. */
export function sketchPatternInstanceCount(spec: SketchPatternSpec): number {
  return spec.kind === "rectangular" ? spec.countX * spec.countY : spec.count;
}

