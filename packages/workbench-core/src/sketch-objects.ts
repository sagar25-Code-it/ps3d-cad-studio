const TWO_PI = Math.PI * 2;

/** The defining points of an entity, in a fixed order. */
export function entityDefiningPoints(entity: SketchEntity): readonly Vec2[] {
  switch (entity.kind) {
    case "line": return [entity.start, entity.end];
    case "arc": return [entity.start, entity.mid, entity.end];
    case "circle": return [entity.center];
    case "ellipse": return [entity.center];
    case "rectangle": return [entity.center];
    case "point": return [entity.point];
    case "spline": return entity.fitPoints;
  }
}

function wrapDegrees(value: number): number {
  const wrapped = ((value % 360) + 360) % 360;
  return wrapped > 180 ? wrapped - 360 : wrapped;
}

/** Maps every defining point through `point` and adds `turnDeg` to the entities that store a rotation. The new entity has `id`. */
export function transformSketchEntity(entity: SketchEntity, id: string, point: (value: Vec2) => Vec2, turnDeg: number): SketchEntity {
  switch (entity.kind) {
    case "line": return { ...entity, id, start: point(entity.start), end: point(entity.end) };
    case "arc": return { ...entity, id, start: point(entity.start), mid: point(entity.mid), end: point(entity.end) };
    case "circle": return { ...entity, id, center: point(entity.center) };
    case "ellipse": return { ...entity, id, center: point(entity.center), rotationDeg: wrapDegrees(entity.rotationDeg + turnDeg) };
    case "rectangle": return { ...entity, id, center: point(entity.center), rotationDeg: wrapDegrees(entity.rotationDeg + turnDeg) };
    case "point": return { ...entity, id, point: point(entity.point) };
    case "spline": return { ...entity, id, fitPoints: entity.fitPoints.map(point) };
  }
}

/** Bounding box of the defining points (circles and rectangles include their size). */
function boundsOfEntities(entities: readonly SketchEntity[]): { readonly min: Vec2; readonly max: Vec2 } {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  const take = (x: number, y: number): void => { minX = Math.min(minX, x); minY = Math.min(minY, y); maxX = Math.max(maxX, x); maxY = Math.max(maxY, y); };
  for (const entity of entities) {
    if (entity.kind === "circle") { take(entity.center[0] - entity.radiusMm, entity.center[1] - entity.radiusMm); take(entity.center[0] + entity.radiusMm, entity.center[1] + entity.radiusMm); continue; }
    if (entity.kind === "ellipse") { take(entity.center[0] - entity.majorRadiusMm, entity.center[1] - entity.majorRadiusMm); take(entity.center[0] + entity.majorRadiusMm, entity.center[1] + entity.majorRadiusMm); continue; }
    if (entity.kind === "rectangle") { const half = Math.hypot(entity.widthMm, entity.heightMm) / 2; take(entity.center[0] - half, entity.center[1] - half); take(entity.center[0] + half, entity.center[1] + half); continue; }
    for (const point of entityDefiningPoints(entity)) take(point[0], point[1]);
  }
  return { min: [minX, minY], max: [maxX, maxY] };
}

