import { ENVELOPE_LIMITS } from "./envelope-limits.js";
import type { SketchEntity, Vec2, WorkbenchSketch, WorkbenchSketchConstraint } from "./types.js";

/**
 * Sketch objects: structured records kept next to the ordinary curves of a sketch.
 *
 * - A text object remembers the string, font, size and layout of sketch text, and the curves it generated, so the text
 *   can be reopened and edited after it was placed.
 * - A pattern object remembers its source curves and its rectangular, circular or path layout. Its instance curves are
 *   ordinary line, arc, circle ... entities with deterministic IDs that the pattern re-generates whenever the source or
 *   the layout changes. Single instances can be suppressed.
 * - An underlay is a locked background picture (the pixels themselves are kept by the application, only the placement,
 *   scale and opacity are part of the sketch).
 *
 * This module is pure geometry and validation so the operation layer, the sketch tools and the tests share one rule set.
 */

export const SKETCH_TEXT_FONTS = ["stroke-1"] as const;
export type SketchTextFont = (typeof SKETCH_TEXT_FONTS)[number];
export type SketchTextAlign = "left" | "center" | "right";

export interface SketchTextObject {
  readonly id: string;
  /** What was typed. The font draws the curves from this. */
  readonly text: string;
  readonly font: SketchTextFont;
  /** Height of a capital letter. */
  readonly heightMm: number;
  /** Stretches the letters sideways (1 is the normal proportion). */
  readonly widthFactor: number;
  /** Multiplies the gap between letters (1 is the default). */
  readonly spacing: number;
  /** Which end of the text sits on `originMm`. */
  readonly align: SketchTextAlign;
  /** Counter-clockwise turn about `originMm`. */
  readonly rotationDeg: number;
  /** The anchor point of the text on the baseline. */
  readonly originMm: Vec2;
  /** The generated curves are construction geometry. */
  readonly construction: boolean;
  /** The generated curves, in drawing order. */
  readonly entityIds: readonly string[];
}

export type SketchPatternSpec =
  | {
      readonly kind: "rectangular";
      readonly countX: number;
      readonly countY: number;
      /** Spacing between neighbours (or the total span when `extent`), along the direction `angleDeg`. */
      readonly dxMm: number;
      readonly dyMm: number;
      /** Direction of the first axis in degrees from +X; the second axis is 90 degrees counter-clockwise from it. */
      readonly angleDeg: number;
      /** dxMm and dyMm are the total span from the first to the last instance instead of the step. */
      readonly extent: boolean;
    }
  | {
      readonly kind: "circular";
      readonly count: number;
      readonly angleDeg: number;
      readonly center: Vec2;
      /** Instances turn with the pattern (true) or keep their orientation and only travel round (false). */
      readonly rotate: boolean;
    }
  | {
      readonly kind: "path";
      readonly pathEntityId: string;
      readonly count: number;
      /** Distance along the path between neighbours when not `fit`. */
      readonly spacingMm: number;
      /** Spread the instances over the whole path (from `startMm` to the end; all the way round for a closed path). */
      readonly fit: boolean;
      readonly startMm: number;
      /** Turn each instance to follow the direction of the path. */
      readonly follow: boolean;
    };

export interface SketchPatternObject {
  readonly id: string;
  readonly spec: SketchPatternSpec;
  /** The curves that are repeated. They are the first instance and stay where they are. */
  readonly sourceIds: readonly string[];
  /** Instance numbers (1 and up; 0 is the source) that are switched off. */
  readonly suppressed: readonly number[];
}

export interface SketchUnderlay {
  readonly name: string;
  /** Names the pixels in the application's image store. */
  readonly imageId: string;
  readonly widthPx: number;
  readonly heightPx: number;
  /** Where the lower left corner of the picture sits in the sketch. */
  readonly originMm: Vec2;
  readonly mmPerPixel: number;
  readonly rotationDeg: number;
  readonly opacity: number;
  /** A locked underlay cannot be picked or dragged. */
  readonly locked: boolean;
  readonly visible: boolean;
}

/** The object part of an `apply-sketch-edit`. */
export interface SketchObjectsEdit {
  /** Text objects to add or replace (by ID). */
  readonly texts?: readonly SketchTextObject[];
  /** Pattern objects to add or replace (by ID). The instance curves are generated by the operation. */
  readonly patterns?: readonly SketchPatternObject[];
  /** Text or pattern objects to forget. The curves they made stay as ordinary geometry (a pattern's instances too). */
  readonly removeObjectIds?: readonly string[];
  /** Replaces the underlay, or removes it with null. */
  readonly underlay?: SketchUnderlay | null;
}

export const SKETCH_PATTERN_MAX_INSTANCES = 101;
export const SKETCH_TEXT_MAX_CHARACTERS = 80;
export const SKETCH_TEXT_MAX_ENTITIES = 400;

// ---------------------------------------------------------------------------------------------------------------------
// Validation
// ---------------------------------------------------------------------------------------------------------------------

const ID_PATTERN = /^[a-z][a-z0-9-]*:[a-z0-9][a-z0-9._-]*$/u;
const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === "object" && value !== null && !Array.isArray(value);
const stableId = (value: unknown): value is string => typeof value === "string" && value.length <= 128 && ID_PATTERN.test(value);
const finite = (value: unknown, minimum: number, maximum: number): value is number => typeof value === "number" && Number.isFinite(value) && value >= minimum && value <= maximum;
const vec2 = (value: unknown): value is Vec2 => Array.isArray(value) && value.length === 2 && value.every((coordinate) => finite(coordinate, -ENVELOPE_LIMITS.maxSketchCoordinateMm, ENVELOPE_LIMITS.maxSketchCoordinateMm));
const keysAre = (value: Record<string, unknown>, expected: readonly string[]): boolean => {
  const actual = Object.keys(value).sort();
  const wanted = [...expected].sort();
  return actual.length === wanted.length && actual.every((key, index) => key === wanted[index]);
};
const integer = (value: unknown, minimum: number, maximum: number): value is number => typeof value === "number" && Number.isInteger(value) && value >= minimum && value <= maximum;
const hasControlCharacter = (text: string): boolean => /[\u0000-\u001f\u007f]/u.test(text);

export function validSketchTextObject(value: unknown): value is SketchTextObject {
  return isRecord(value)
    && keysAre(value, ["id", "text", "font", "heightMm", "widthFactor", "spacing", "align", "rotationDeg", "originMm", "construction", "entityIds"])
    && stableId(value.id) && value.id.startsWith("text:")
    && typeof value.text === "string" && value.text.trim().length >= 1 && value.text.length <= SKETCH_TEXT_MAX_CHARACTERS && !hasControlCharacter(value.text)
    && (SKETCH_TEXT_FONTS as readonly unknown[]).includes(value.font)
    && finite(value.heightMm, 0.5, 1_000) && finite(value.widthFactor, 0.2, 5) && finite(value.spacing, 0, 10)
    && (value.align === "left" || value.align === "center" || value.align === "right")
    && finite(value.rotationDeg, -360, 360) && vec2(value.originMm) && typeof value.construction === "boolean"
    && Array.isArray(value.entityIds) && value.entityIds.length >= 1 && value.entityIds.length <= SKETCH_TEXT_MAX_ENTITIES && value.entityIds.every(stableId)
    && new Set(value.entityIds).size === value.entityIds.length;
}

export function validSketchPatternSpec(value: unknown): value is SketchPatternSpec {
  if (!isRecord(value)) return false;
  if (value.kind === "rectangular") {
    return keysAre(value, ["kind", "countX", "countY", "dxMm", "dyMm", "angleDeg", "extent"])
      && integer(value.countX, 1, SKETCH_PATTERN_MAX_INSTANCES) && integer(value.countY, 1, SKETCH_PATTERN_MAX_INSTANCES)
      && (value.countX as number) * (value.countY as number) >= 2 && (value.countX as number) * (value.countY as number) <= SKETCH_PATTERN_MAX_INSTANCES
      && finite(value.dxMm, -100_000, 100_000) && finite(value.dyMm, -100_000, 100_000) && finite(value.angleDeg, -360, 360) && typeof value.extent === "boolean";
  }
  if (value.kind === "circular") {
    return keysAre(value, ["kind", "count", "angleDeg", "center", "rotate"])
      && integer(value.count, 2, SKETCH_PATTERN_MAX_INSTANCES) && finite(value.angleDeg, -360, 360) && vec2(value.center) && typeof value.rotate === "boolean";
  }
  if (value.kind === "path") {
    return keysAre(value, ["kind", "pathEntityId", "count", "spacingMm", "fit", "startMm", "follow"])
      && stableId(value.pathEntityId) && integer(value.count, 2, SKETCH_PATTERN_MAX_INSTANCES) && finite(value.spacingMm, 0, 100_000)
      && typeof value.fit === "boolean" && finite(value.startMm, 0, 100_000) && typeof value.follow === "boolean";
  }
  return false;
}

export function validSketchPatternObject(value: unknown): value is SketchPatternObject {
  return isRecord(value) && keysAre(value, ["id", "spec", "sourceIds", "suppressed"])
    && stableId(value.id) && value.id.startsWith("pattern:") && validSketchPatternSpec(value.spec)
    && Array.isArray(value.sourceIds) && value.sourceIds.length >= 1 && value.sourceIds.length <= 100 && value.sourceIds.every(stableId) && new Set(value.sourceIds).size === value.sourceIds.length
    && Array.isArray(value.suppressed) && value.suppressed.length <= SKETCH_PATTERN_MAX_INSTANCES && value.suppressed.every((index) => integer(index, 1, SKETCH_PATTERN_MAX_INSTANCES))
    && new Set(value.suppressed).size === value.suppressed.length;
}

export function validSketchUnderlay(value: unknown): value is SketchUnderlay {
  return isRecord(value) && keysAre(value, ["name", "imageId", "widthPx", "heightPx", "originMm", "mmPerPixel", "rotationDeg", "opacity", "locked", "visible"])
    && typeof value.name === "string" && value.name.length >= 1 && value.name.length <= 120 && !hasControlCharacter(value.name)
    && typeof value.imageId === "string" && /^[a-z0-9][a-z0-9-]{3,63}$/u.test(value.imageId)
    && integer(value.widthPx, 1, 16_384) && integer(value.heightPx, 1, 16_384)
    && Array.isArray(value.originMm) && value.originMm.length === 2 && value.originMm.every((part) => finite(part, -100_000, 100_000))
    && finite(value.mmPerPixel, 1e-4, 1_000) && finite(value.rotationDeg, -360, 360) && finite(value.opacity, 0.05, 1)
    && typeof value.locked === "boolean" && typeof value.visible === "boolean";
}

export function validSketchObjectsEdit(value: unknown): value is SketchObjectsEdit {
  if (!isRecord(value)) return false;
  const allowed = ["texts", "patterns", "removeObjectIds", "underlay"];
  if (Object.keys(value).some((key) => !allowed.includes(key))) return false;
  if (Object.hasOwn(value, "texts") && !(Array.isArray(value.texts) && value.texts.length <= 50 && value.texts.every(validSketchTextObject))) return false;
  if (Object.hasOwn(value, "patterns") && !(Array.isArray(value.patterns) && value.patterns.length <= 50 && value.patterns.every(validSketchPatternObject))) return false;
  if (Object.hasOwn(value, "removeObjectIds") && !(Array.isArray(value.removeObjectIds) && value.removeObjectIds.length <= 100 && value.removeObjectIds.every(stableId))) return false;
  if (Object.hasOwn(value, "underlay") && value.underlay !== null && !validSketchUnderlay(value.underlay)) return false;
  return true;
}

/**
 * Whether the three optional object fields of a stored sketch are well formed and refer only to entities that exist.
 * `record` is the raw sketch; the entity IDs are those it holds.
 */
export function validSketchObjectFields(record: Record<string, unknown>, entityIds: ReadonlySet<string>): boolean {
  const ids = new Set<string>();
  if (Object.hasOwn(record, "texts")) {
    if (!Array.isArray(record.texts) || record.texts.length > 100) return false;
    const owned = new Set<string>();
    for (const text of record.texts) {
      if (!validSketchTextObject(text) || ids.has(text.id) || text.entityIds.some((id) => !entityIds.has(id) || owned.has(id))) return false;
      ids.add(text.id);
      for (const id of text.entityIds) owned.add(id);
    }
  }
  if (Object.hasOwn(record, "patterns")) {
    if (!Array.isArray(record.patterns) || record.patterns.length > 100) return false;
    for (const pattern of record.patterns) {
      if (!validSketchPatternObject(pattern) || ids.has(pattern.id) || pattern.sourceIds.some((id) => !entityIds.has(id))) return false;
      if (pattern.spec.kind === "path" && (!entityIds.has(pattern.spec.pathEntityId) || pattern.sourceIds.includes(pattern.spec.pathEntityId))) return false;
      ids.add(pattern.id);
    }
  }
  if (Object.hasOwn(record, "underlay") && !validSketchUnderlay(record.underlay)) return false;
  return true;
}

