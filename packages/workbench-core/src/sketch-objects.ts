export type SketchObjectsResult =
  | { readonly ok: true; readonly sketch: WorkbenchSketch; readonly notes: readonly string[] }
  | { readonly ok: false; readonly message: string; readonly relatedIds: readonly string[] };

function withoutObjectFields(sketch: WorkbenchSketch, fields: { readonly texts?: readonly SketchTextObject[] | undefined; readonly patterns?: readonly SketchPatternObject[] | undefined; readonly underlay?: SketchUnderlay | null | undefined }): WorkbenchSketch {
  const { texts: _texts, patterns: _patterns, underlay: _underlay, ...rest } = sketch;
  const texts = "texts" in fields ? fields.texts : sketch.texts;
  const patterns = "patterns" in fields ? fields.patterns : sketch.patterns;
  const underlay = "underlay" in fields ? fields.underlay : sketch.underlay;
  return {
    ...rest,
    ...(texts === undefined || texts.length === 0 ? {} : { texts }),
    ...(patterns === undefined || patterns.length === 0 ? {} : { patterns }),
    ...(underlay === undefined || underlay === null ? {} : { underlay })
  };
}

/** Removes the three object fields (used when a sketch is cleared for a fresh start). */
export function sketchWithoutObjects(sketch: WorkbenchSketch): WorkbenchSketch {
  const { texts: _texts, patterns: _patterns, underlay: _underlay, ...rest } = sketch;
  return rest;
}

/** Applies the object part of an edit to a sketch whose entities are already final: upserts, removals and the underlay. */
export function applySketchObjectsEdit(sketch: WorkbenchSketch, edit: SketchObjectsEdit | undefined): WorkbenchSketch {
  if (edit === undefined) return sketch;
  const remove = new Set(edit.removeObjectIds ?? []);
  const textIds = new Set((edit.texts ?? []).map((text) => text.id));
  const patternIds = new Set((edit.patterns ?? []).map((pattern) => pattern.id));
  const texts = [...(sketch.texts ?? []).filter((text) => !remove.has(text.id) && !textIds.has(text.id)), ...(edit.texts ?? [])];
  const patterns = [...(sketch.patterns ?? []).filter((pattern) => !remove.has(pattern.id) && !patternIds.has(pattern.id)), ...(edit.patterns ?? [])];
  return withoutObjectFields(sketch, { texts, patterns, ...(Object.hasOwn(edit, "underlay") ? { underlay: edit.underlay } : {}) });
}

/** The IDs of objects an edit sets or removes: reconcile leaves these alone. */
export function explicitObjectIds(edit: SketchObjectsEdit | undefined): ReadonlySet<string> {
  return new Set([...(edit?.texts ?? []).map((text) => text.id), ...(edit?.patterns ?? []).map((pattern) => pattern.id), ...(edit?.removeObjectIds ?? [])]);
}

/** The shift that maps entity `a` onto entity `b`, if they are the same shape moved without turning or resizing. */
function translationBetween(a: SketchEntity, b: SketchEntity): Vec2 | undefined {
  if (a.kind !== b.kind) return undefined;
  if (a.kind === "circle" && b.kind === "circle" && a.radiusMm !== b.radiusMm) return undefined;
  if (a.kind === "rectangle" && b.kind === "rectangle" && (a.widthMm !== b.widthMm || a.heightMm !== b.heightMm || a.rotationDeg !== b.rotationDeg)) return undefined;
  if (a.kind === "ellipse" && b.kind === "ellipse" && (a.majorRadiusMm !== b.majorRadiusMm || a.minorRadiusMm !== b.minorRadiusMm || a.rotationDeg !== b.rotationDeg)) return undefined;
  const pa = entityDefiningPoints(a);
  const pb = entityDefiningPoints(b);
  if (pa.length !== pb.length || pa.length === 0) return undefined;
  const dx = pb[0]![0] - pa[0]![0];
  const dy = pb[0]![1] - pa[0]![1];
  for (let index = 1; index < pa.length; index += 1) {
    if (Math.abs(pb[index]![0] - pa[index]![0] - dx) > 1e-6 || Math.abs(pb[index]![1] - pa[index]![1] - dy) > 1e-6) return undefined;
  }
  return [dx, dy];
}

const sameEntity = (a: SketchEntity, b: SketchEntity): boolean => a === b || JSON.stringify(a) === JSON.stringify(b);

/**
 * After any operation: drops text objects whose curves were deleted or reshaped (a pure move carries the text along), and
 * re-generates the instance curves of every pattern from its sources. `previous` is the sketch before the operation and
 * `explicit` the objects the operation itself set or removed.
 */
export function reconcileSketchObjects(previous: WorkbenchSketch, next: WorkbenchSketch, explicit: ReadonlySet<string>): SketchObjectsResult {
  if ((next.texts === undefined || next.texts.length === 0) && (next.patterns === undefined || next.patterns.length === 0)) return { ok: true, sketch: next, notes: [] };
  const notes: string[] = [];
  const previousEntities = new Map(previous.entities.map((entity) => [entity.id, entity] as const));
  let entities: SketchEntity[] = [...next.entities];
  let constraints: readonly WorkbenchSketchConstraint[] = next.constraints;

  const texts: SketchTextObject[] = [];
  for (const text of next.texts ?? []) {
    if (explicit.has(text.id)) { texts.push(text); continue; }
    const current = text.entityIds.map((id) => entities.find((entity) => entity.id === id));
    if (current.every((entity) => entity === undefined)) continue;
    if (current.some((entity) => entity === undefined)) { notes.push(`Text "${text.text}" lost some curves and is now plain geometry.`); continue; }
    const before = text.entityIds.map((id) => previousEntities.get(id));
    if (before.some((entity) => entity === undefined) || before.every((entity, index) => sameEntity(entity!, current[index]!))) { texts.push(text); continue; }
    const shifts = before.map((entity, index) => translationBetween(entity!, current[index]!));
    const first = shifts[0];
    // Moving every curve together, or switching them all to construction (or back), keeps the text editable.
    const uniformFlag = current.every((entity) => entity!.construction === current[0]!.construction);
    if (uniformFlag && first !== undefined && shifts.every((shift) => shift !== undefined && Math.abs(shift[0] - first[0]) < 1e-6 && Math.abs(shift[1] - first[1]) < 1e-6)) {
      texts.push({ ...text, originMm: [text.originMm[0] + first[0], text.originMm[1] + first[1]], construction: current[0]!.construction });
    } else notes.push(`Text "${text.text}" was reshaped by hand and is now plain geometry.`);
  }

  const patterns: SketchPatternObject[] = [];
  const limit = 500;
  for (const pattern of next.patterns ?? []) {
    const sourcesPresent = pattern.sourceIds.every((id) => entities.some((entity) => entity.id === id))
      && (pattern.spec.kind !== "path" || entities.some((entity) => entity.id === (pattern.spec as { readonly pathEntityId: string }).pathEntityId));
    if (!sourcesPresent) { notes.push("A pattern lost its source or path curve and its copies are now plain geometry."); continue; }
    // An instance whose every curve was deleted by hand is switched off instead of coming back.
    let suppressed = pattern.suppressed;
    if (!explicit.has(pattern.id)) {
      const known = new Map<number, { total: number; gone: number }>();
      for (const entity of previous.entities) {
        const instance = sketchPatternInstanceOf(pattern.id, entity.id);
        if (instance === undefined) continue;
        const slot = known.get(instance) ?? { total: 0, gone: 0 };
        slot.total += 1;
        if (!entities.some((candidate) => candidate.id === entity.id)) slot.gone += 1;
        known.set(instance, slot);
      }
      const newlyOff = [...known.entries()].filter(([instance, slot]) => slot.total > 0 && slot.gone === slot.total && !suppressed.includes(instance)).map(([instance]) => instance);
      if (newlyOff.length > 0) suppressed = [...suppressed, ...newlyOff].sort((a, b) => a - b);
    }
    const current: SketchPatternObject = suppressed === pattern.suppressed ? pattern : { ...pattern, suppressed };
    const generated = generateSketchPatternEntities(current, entities);
    if (!generated.ok) {
      if (explicit.has(pattern.id)) return { ok: false, message: generated.message, relatedIds: [pattern.id] };
      notes.push(`${generated.message} The pattern copies were kept as plain geometry.`);
      continue;
    }
    const wanted = new Map(generated.entities.map((entity) => [entity.id, entity] as const));
    const prefix = sketchPatternInstancePrefix(pattern.id);
    const stale = entities.filter((entity) => entity.id.startsWith(prefix) && !wanted.has(entity.id)).map((entity) => entity.id);
    const staleSet = new Set(stale);
    let reset = 0;
    const kept = entities.filter((entity) => !staleSet.has(entity.id)).map((entity) => {
      const target = wanted.get(entity.id);
      if (target === undefined) return entity;
      wanted.delete(entity.id);
      if (sameEntity(entity, target)) return entity;
      if (previousEntities.has(entity.id) && sameEntity(previousEntities.get(entity.id)!, entity)) return target;
      reset += 1;
      return target;
    });
    const added = [...wanted.values()];
    if (kept.length + added.length > limit) return { ok: false, message: `The pattern would make ${kept.length + added.length} curves in the sketch; the limit is ${limit}. Use fewer instances or fewer source curves.`, relatedIds: [pattern.id] };
    entities = [...kept, ...added];
    if (staleSet.size > 0) constraints = constraints.filter((constraint) => !constraint.entityIds.some((id) => staleSet.has(id)));
    if (reset > 0) notes.push(`${reset} pattern curve${reset === 1 ? " was" : "s were"} reset to follow the pattern; edit the source curves or the pattern instead.`);
    patterns.push(current);
  }

  const sketch = withoutObjectFields({ ...next, entities, constraints }, { texts, patterns });
  return { ok: true, sketch, notes };
}
